"""Loads data/menu_map.json into MenuItem objects.

data/menu_map.json is generated by scripts/build_menu_map.py from data/raw/*.json.
The file location can be changed with the SEJONG_MENU_MAP environment variable.

Accepted schema (version 2): the required fields below, plus the optional
name_en_site, selector_desktop, selector_mobile, mobile_path_note, frame,
opens_new_tab and keywords. A map in the older format (a single "selector",
as the extension's recorder exports it) still loads: its selector is used as
selector_desktop.
"""
from __future__ import annotations

import json
import os
from functools import lru_cache
from pathlib import Path

from core.models import SITES, MenuItem

DEFAULT_MENU_MAP = Path(__file__).resolve().parent.parent / "data" / "menu_map.json"
REQUIRED_FIELDS = ("id", "site", "name_ko", "name_en", "parent_id", "url", "description")
OPTIONAL_TEXT_FIELDS = ("name_en_site", "selector_desktop", "selector_mobile", "mobile_path_note", "frame")


def menu_map_path() -> Path:
    """Return the menu map path: SEJONG_MENU_MAP if set, otherwise the default."""
    return Path(os.environ.get("SEJONG_MENU_MAP", DEFAULT_MENU_MAP))


def _item_from_entry(entry: dict) -> MenuItem:
    item_id = entry.get("id")
    missing = [f for f in REQUIRED_FIELDS if f not in entry]
    if missing:
        raise ValueError(f"menu item {item_id!r} is missing fields: {missing}")
    if entry["site"] not in SITES:
        raise ValueError(f"menu item {item_id!r} has unknown site {entry['site']!r}")
    keywords = entry.get("keywords", [])
    if not (isinstance(keywords, list) and all(isinstance(k, str) and k.strip() for k in keywords)):
        raise ValueError(f"menu item {item_id!r}: keywords must be a list of strings")
    optional = {f: entry.get(f) for f in OPTIONAL_TEXT_FIELDS}
    if "selector_desktop" not in entry and "selector_mobile" not in entry:
        optional["selector_desktop"] = entry.get("selector")  # older format
    for field, value in optional.items():
        if value is not None and not isinstance(value, str):
            raise ValueError(f"menu item {item_id!r}: {field} must be a string or null")
    opens_new_tab = entry.get("opens_new_tab", False)
    if not isinstance(opens_new_tab, bool):
        raise ValueError(f"menu item {item_id!r}: opens_new_tab must be true or false")
    return MenuItem(**{f: entry[f] for f in REQUIRED_FIELDS}, keywords=tuple(keywords),
                    opens_new_tab=opens_new_tab, **optional)


@lru_cache(maxsize=1)
def load_menu_items() -> dict[str, MenuItem]:
    """Read the menu map and return {id: MenuItem}.

    Only basic shape checks happen here: required fields, field types, a valid site,
    unique ids and parent ids that exist. scripts/build_menu_map.py and
    tests/test_menu_map.py check more (cycles, links between sites).

    Raises:
        ValueError: if the file has the wrong shape.
    """
    raw = json.loads(menu_map_path().read_text(encoding="utf-8"))
    items: dict[str, MenuItem] = {}
    for entry in raw["items"]:
        item = _item_from_entry(entry)
        if item.id in items:
            raise ValueError(f"duplicate menu item id {item.id!r}")
        items[item.id] = item

    for item in items.values():
        if item.parent_id is not None and item.parent_id not in items:
            raise ValueError(f"menu item {item.id!r} has unknown parent {item.parent_id!r}")
    return items

"""Merge data/raw/*.json into data/menu_map.json (and the extension's copy).

    .venv/bin/python scripts/build_menu_map.py           # build, validate, write, print a summary
    .venv/bin/python scripts/build_menu_map.py --check   # only check that menu_map.json is up to date

data/raw/<site>.json holds the items recorded from one live site: a JSON list
(or {"items": [...]}) of objects with exactly the fields in FIELDS. The raw
files have one top-level tree per menu group and no links between sites, so the
build adds the links that routing needs:

  * portal.root (the portal main page) is added, and every portal item without a
    parent hangs under it. Every route starts there (ROOT_ID in extension/config.js).
  * Every top-level item of another site hangs under that site's ENTRY_POINTS item.
    portal.sjpt opens SJPT in a new tab, so all SJPT top tabs hang under it, and a
    route from the portal to any SJPT item has to go through portal.sjpt
    (likewise e-Campus under portal.ecampus and the library under portal.library).

Checks (the build stops and lists every problem): field names and types, known
sites, unique ids, every parent_id exists, no cycles, a single root, and links
between sites only through ENTRY_POINTS.
"""
from __future__ import annotations

import argparse
import html
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from core.models import SITES  # noqa: E402  (needs the sys.path line above)

RAW_DIR = ROOT / "data" / "raw"
OUTPUT = ROOT / "data" / "menu_map.json"
EXTENSION_COPY = ROOT / "extension" / "data" / "menu_map.json"

# Field name -> allowed JSON types. The output keeps this order.
STR, OPT_STR = (str,), (str, type(None))
FIELDS = {
    "id": STR, "site": STR, "name_ko": STR, "name_en": STR, "name_en_site": OPT_STR,
    "parent_id": OPT_STR, "url": OPT_STR, "selector_desktop": OPT_STR, "selector_mobile": OPT_STR,
    "mobile_path_note": OPT_STR, "frame": OPT_STR, "opens_new_tab": (bool,),
    "description": STR, "keywords": (list,),
}

ROOT_ID = "portal.root"
SYNTHETIC_ROOT = {
    "id": ROOT_ID, "site": "portal", "name_ko": "세종대학교 포털", "name_en": "Sejong University Portal",
    "name_en_site": None, "parent_id": None, "url": "https://portal.sejong.ac.kr",
    "selector_desktop": None, "selector_mobile": None, "mobile_path_note": None, "frame": None,
    "opens_new_tab": False,
    "description": "Portal main page after login. Entry point to SJPT, e-Campus and the library.",
    "keywords": ["portal", "bosh sahifa", "asosiy sahifa", "home", "main page", "포털", "메인"],
}
# site -> the portal item that opens it (both open in a new tab). Top-level items of the
# site hang under it, so routes into the site always pass through it.
ENTRY_POINTS = {"sjpt": "portal.sjpt", "ecampus": "portal.ecampus", "library": "portal.library"}

COMMENT = ("AI-generated — to be rewritten by me. GENERATED by scripts/build_menu_map.py from "
           "data/raw/*.json: edit those files, not this one. portal.root is added by the build, "
           "and the top-level items of each site are linked to the portal item that opens it.")


class MenuMapError(ValueError):
    """The raw data is invalid. ``problems`` lists every issue found."""

    def __init__(self, problems: list[str]) -> None:
        super().__init__("\n".join(problems))
        self.problems = problems


def read_raw(raw_dir: Path) -> list[tuple[str, dict]]:
    """[(file name, raw item)] from every *.json in raw_dir, in file-name order."""
    entries = []
    for path in sorted(raw_dir.glob("*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        items = data["items"] if isinstance(data, dict) else data
        if not isinstance(items, list):
            raise MenuMapError([f"{path.name}: expected a list of items"])
        entries += [(path.name, item) for item in items]
    return entries


def _shape_problems(source: str, item) -> list[str]:
    if not isinstance(item, dict):
        return [f"{source}: item is not an object: {item!r}"]
    where = f"{source}: {item.get('id', '<no id>')!r}"
    problems = []
    missing = [f for f in FIELDS if f not in item]
    extra = [f for f in item if f not in FIELDS]
    if missing:
        problems.append(f"{where} is missing fields {missing}")
    if extra:
        problems.append(f"{where} has unknown fields {extra}")
    for field, types in FIELDS.items():
        if field in item and not isinstance(item[field], types):
            problems.append(f"{where}: {field} has type {type(item[field]).__name__}")
    for field in ("id", "name_ko", "name_en"):
        if isinstance(item.get(field), str) and not item[field].strip():
            problems.append(f"{where}: {field} is empty")
    keywords = item.get("keywords")
    if isinstance(keywords, list) and not all(isinstance(k, str) and k.strip() for k in keywords):
        problems.append(f"{where}: keywords must be non-empty strings")
    if isinstance(item.get("site"), str) and item["site"] not in SITES:
        problems.append(f"{where}: unknown site {item['site']!r}")
    return problems


def find_cycles(items: dict[str, dict]) -> list[list[str]]:
    """Every parent_id cycle, each as [id, ..., id] (the first id repeated at the end)."""
    state: dict[str, str] = {}  # id -> "open" while walking up from it, "done" afterwards
    cycles = []
    for start in sorted(items):
        chain = []
        node = start
        while node in items and state.get(node) is None:
            state[node] = "open"
            chain.append(node)
            node = items[node]["parent_id"]
        if node in items and state.get(node) == "open":
            cycles.append(chain[chain.index(node):] + [node])
        for visited in chain:
            state[visited] = "done"
    return cycles


def build(raw_dir: Path = RAW_DIR) -> tuple[list[dict], dict]:
    """Merge and validate. Returns (items in output order, summary numbers).

    Raises:
        MenuMapError: listing every problem, if anything is wrong.
    """
    entries = read_raw(raw_dir)
    problems = [p for source, item in entries for p in _shape_problems(source, item)]
    if problems:
        raise MenuMapError(problems)

    items: dict[str, dict] = {}
    sources: dict[str, str] = {}
    for source, raw in entries:
        if raw["id"] in items:
            problems.append(f"{source}: duplicate id {raw['id']!r} (also in {sources[raw['id']]})")
            continue
        items[raw["id"]] = {field: raw[field] for field in FIELDS}
        sources[raw["id"]] = source
    if ROOT_ID in items:
        problems.append(f"{sources[ROOT_ID]}: {ROOT_ID!r} is added by the build; remove it from the raw data")
    for site, entry in ENTRY_POINTS.items():
        if entry not in items:
            problems.append(f"entry point {entry!r} for site {site!r} is not in the raw data")
    if problems:
        raise MenuMapError(problems)

    # Link the top-level items: portal ones under portal.root, other sites under their entry point.
    linked = Counter()
    for item in items.values():
        if item["parent_id"] is not None:
            continue
        if item["site"] == "portal":
            item["parent_id"] = ROOT_ID
        elif item["site"] in ENTRY_POINTS:
            item["parent_id"] = ENTRY_POINTS[item["site"]]
        else:
            problems.append(f"{item['id']!r}: site {item['site']!r} has no entry point in ENTRY_POINTS")
            continue
        linked[item["site"]] += 1
    items = {ROOT_ID: dict(SYNTHETIC_ROOT), **items}

    for item in items.values():
        parent = item["parent_id"]
        if parent is not None and parent not in items:
            problems.append(f"{item['id']!r}: parent_id {parent!r} does not exist")
        elif parent is not None and items[parent]["site"] != item["site"]:
            allowed = item["site"] in ENTRY_POINTS and parent == ENTRY_POINTS[item["site"]]
            if not allowed:
                problems.append(f"{item['id']!r} ({item['site']}) has parent {parent!r} on another site; "
                                f"sites may only link through ENTRY_POINTS")
    if problems:
        raise MenuMapError(problems)
    problems += [f"cycle: {' -> '.join(c)}" for c in find_cycles(items)]
    roots = [i["id"] for i in items.values() if i["parent_id"] is None]
    if roots != [ROOT_ID]:
        problems.append(f"expected exactly one root ({ROOT_ID}), found {roots}")
    if problems:
        raise MenuMapError(problems)

    ordered = list(items.values())
    summary = {
        "files": sorted({source for source, _ in entries}),
        "items": len(ordered),
        "per_site": dict(Counter(i["site"] for i in ordered)),
        "linked": dict(linked),
        "no_english_site_label": dict(Counter(i["site"] for i in ordered[1:] if i["name_en_site"] is None)),
        "text_fallback_only": sorted(i["id"] for i in ordered[1:]
                                     if not i["selector_desktop"] and not i["selector_mobile"]),
        "opens_new_tab": sum(i["opens_new_tab"] for i in ordered),
        "html_entities": sorted(i["id"] for i in ordered
                                if i["name_en_site"] and html.unescape(i["name_en_site"]) != i["name_en_site"]),
        "max_depth": max(_depth(items, i["id"]) for i in ordered),
    }
    return ordered, summary


def _depth(items: dict[str, dict], item_id: str) -> int:
    depth = 0
    while items[item_id]["parent_id"] is not None:
        item_id = items[item_id]["parent_id"]
        depth += 1
    return depth


def render(items: list[dict]) -> str:
    """The exact text of data/menu_map.json."""
    data = {"_comment": COMMENT, "version": 2, "items": items}
    return json.dumps(data, ensure_ascii=False, indent=2) + "\n"


def print_summary(summary: dict, wrote: bool) -> None:
    sites = ", ".join(f"{site} {n}" for site, n in summary["per_site"].items())
    linked = ", ".join(f"{n} {site}" for site, n in summary["linked"].items())
    no_en = ", ".join(f"{site} {n}" for site, n in summary["no_english_site_label"].items()) or "none"
    print(f"read {', '.join(summary['files'])}")
    print(f"items: {summary['items']} ({sites}; includes the added {ROOT_ID})")
    print(f"linked top-level items: {linked} "
          f"(portal -> {ROOT_ID}, " + ", ".join(f"{s} -> {e}" for s, e in ENTRY_POINTS.items()) + ")")
    print(f"deepest item: {summary['max_depth']} clicks below {ROOT_ID}")
    print(f"opens a new tab: {summary['opens_new_tab']}")
    print(f"no English site label (name_en_site null): {no_en}")
    print(f"no selector, found by text only: {len(summary['text_fallback_only'])}")
    if summary["html_entities"]:
        print(f"name_en_site with HTML entities (decoded when matching): {', '.join(summary['html_entities'])}")
    print("checks passed: fields, sites, unique ids, parents exist, no cycles, one root, cross-site links")
    if wrote:
        print(f"wrote {OUTPUT.relative_to(ROOT)} and {EXTENSION_COPY.relative_to(ROOT)}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if menu_map.json is not up to date; write nothing")
    args = parser.parse_args(argv)
    try:
        items, summary = build()
    except MenuMapError as error:
        print(f"menu map NOT built, {len(error.problems)} problem(s):", file=sys.stderr)
        for problem in error.problems:
            print(f"  - {problem}", file=sys.stderr)
        return 1
    text = render(items)
    if args.check:
        stale = [p for p in (OUTPUT, EXTENSION_COPY) if not p.exists() or p.read_text(encoding="utf-8") != text]
        print_summary(summary, wrote=False)
        for path in stale:
            print(f"OUT OF DATE: {path.relative_to(ROOT)} (run scripts/build_menu_map.py)", file=sys.stderr)
        return 1 if stale else 0
    for path in (OUTPUT, EXTENSION_COPY):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    print_summary(summary, wrote=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
